/* USER CODE BEGIN 4 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
	if(! xQueueIsQueueFullFromISR( queue_data ))
	{
		/*Queue is not full */

		/* Enqueue data byte */
        xQueueSendFromISR( queue_data,(void*)&user_data,NULL );

	}else
  {
		/*Queue is full */
    uint8_t dummy_read;
		if(user_data =='\n')
		{
			/*user_data = '\n' */

			/* make sure that last data byte of the queue is '\n' */
			//before we add the data to back of the queue we neee to remove the already present data at the end.A data item form the queue is removed by reading the data from queue using the API xQueueReceive.
			xQueueReceiveFromISR(queue_data,(void*)&dummy_read, NULL);
            xQueueSendToBackFromISR(queue_data,(void*)&user_data,NULL);
		}
	}


	/* send notification to command handling task if user_data = '\n' */
  if(user_data == '\n')
  {
    xTaskNotifyFromISR(handle_cmd_task,0,eNoAction,NULL);
  }

	/*  Enable UART data byte reception again in IT mode */
  //We do the explicit type casting here((void*)&user_data) because in FreeRtos queue operations we do not queue the pointer we, queue the data pointed by pointer
  //hence we type cast it to a generic pointer type as the related api uses a generic type pointer. This means the data could be char,int ,long,etc,any type.
  HAL_UART_Receive_IT(&huart2, (void*)&user_data, 1);

}

/* WHen timer expires based on the timer ID that expires we will call the respective LED effects based functions. The led_effect() function is used to start the timers and stop the previous LED_effects.*/
void led_effect_callback(TimerHandle_t xTimer)
{
	int id;
	id = ( uint32_t ) pvTimerGetTimerID( xTimer );

	switch(id)
	{
	case 1:
		LED_effect1();
		break;
	case 2:
		LED_effect2();
		break;
	case 3:
		LED_effect3();
		break;
	case 4:
		LED_effect4();
		break;
	default:
		break;
	}
}

